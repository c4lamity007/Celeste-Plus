class NativeBudgetTests(unittest.TestCase):
    setUp = fixture.NativeAuthResourceTests.setUp
    write = fixture.NativeAuthResourceTests.write
    load = fixture.NativeAuthResourceTests.load
    package_args = fixture.NativeAuthResourceTests.package_args

    def output(self, size):
        data = fixture.dll() + b"x" * (size - len(fixture.dll()))
        self.entries[self.resource] = data
        self.evidence["output"] = data
        self.item.update(size=len(data), sha256=subject.sha(data))
        (self.root / "output").write_bytes(data)
        self.approved["evidence"]["output"].update(size=len(data), sha256=subject.sha(data))
        custody = json.loads(self.evidence["custody"])
        custody["final_dll_sha256"] = self.item["sha256"]
        raw = json.dumps(custody).encode()
        self.evidence["custody"] = raw
        (self.root / "custody").write_bytes(raw)
        self.item["custody_sha256"] = subject.sha(raw)
        self.approved["evidence"]["custody"].update(size=len(raw), sha256=subject.sha(raw))
        self.write()
        return data

    def test_real_sized_approved_dll_passes_both_readers_and_final_assembly(self):
        data = self.output(20_523_520)
        approval = self.load()
        encoded = pack.zip_bytes(self.entries)
        jar = self.root / "native.jar"; jar.write_bytes(encoded)
        self.assertEqual(data, pack.read_zip(encoded, "fixture", approval)[self.resource])
        self.assertEqual(data, pipeline.archive(jar, approval)[self.resource])
        with self.assertRaises(ValueError): pack.read_zip(encoded, "default")
        with self.assertRaises(ValueError): pipeline.archive(jar)
        with self.assertRaises(ValueError): pack.read_zip(encoded, "wrong-role", approval, "bootstrap-a")
        args = self.package_args()
        pack.assemble(args)
        self.assertEqual(4, len(json.loads((args.output / "beta-release.json").read_bytes())["artifacts"]))

    def test_renamed_or_hash_changed_large_bytes_do_not_get_exception(self):
        data = self.output(subject.MAX_ENTRY + 1)
        approval = self.load()
        for values in ({self.resource: data[:-1] + b"y"}, {"META-INF/renamed.random": data}):
            encoded = pack.zip_bytes(values)
            jar = self.root / "bad.jar"; jar.write_bytes(encoded)
            with self.assertRaises(ValueError): pack.read_zip(encoded, "tamper", approval)
            with self.assertRaises(ValueError): pipeline.archive(jar, approval)

    def test_metadata_or_self_declared_budget_does_not_raise_default_limit(self):
        data = self.output(subject.MAX_ENTRY + 1)
        encoded = pack.zip_bytes(self.entries | {subject.BUDGET_RESOURCE: subject.budget_bytes(self.load())})
        with self.assertRaises(ValueError): pack.read_zip(encoded, "untrusted")
        jar = self.root / "self.jar"; jar.write_bytes(encoded)
        with self.assertRaises(ValueError): pipeline.archive(jar)
        # Even a correctly serialized index must be generated by package prepare.
        jar.write_bytes(pack.zip_bytes({subject.BUDGET_RESOURCE: b"celeste-native-auth-budget-1\n"}))
        with self.assertRaisesRegex(ValueError, "own native budget"):
            pack.prepare(SimpleNamespace(input=jar, release_id="fixture-release-1"))

    def test_native_bounds_count_and_aggregate_are_checked_before_evidence_io(self):
        for size in (89, subject.MAX_NATIVE_ENTRY + 1, True):
            self.item["size"] = size; self.write()
            with self.assertRaisesRegex(ValueError, "native entry bound"): self.load()
        self.item["size"] = subject.MAX_NATIVE_ENTRY
        self.inventory["resources"] = [copy.deepcopy(self.item) for _ in range(3)]
        self.index["approvals"] = [copy.deepcopy(self.approved) for _ in range(3)]
        self.write()
        with self.assertRaisesRegex(ValueError, "aggregate"): self.load()
        self.inventory["resources"] = [copy.deepcopy(self.item) for _ in range(5)]
        self.index["approvals"] = [copy.deepcopy(self.approved) for _ in range(5)]
        self.write()
        with self.assertRaisesRegex(ValueError, "count"): self.load()

    def test_non_dll_evidence_and_ordinary_resources_keep_eight_mib_bound(self):
        self.output(subject.MAX_ENTRY + 1)
        self.approved["evidence"]["source"]["size"] = subject.MAX_ENTRY + 1
        self.write()
        with self.assertRaisesRegex(ValueError, "evidence reference"): self.load()
        self.approved["evidence"]["source"]["size"] = len(self.evidence["source"])
        self.write(); approval = self.load()
        with self.assertRaises(ValueError):
            subject.validate_entries(self.entries | {"assets/large.png": b"x" * (subject.MAX_ENTRY + 1)}, "payload", approval)
        self.assertEqual(8 * 1024 * 1024, pack.MAX_FILE)
        self.assertEqual(64 * 1024 * 1024, pack.MAX_PART)
        self.assertEqual(128 * 1024 * 1024, pack.MAX_TOTAL)
        self.assertEqual(128 * 1024 * 1024, pipeline.MAX_JAR)

    def test_index_is_exact_canonical_sorted_ascii_and_legacy_absent(self):
        approval = self.load()
        expected = f"celeste-native-auth-budget-1\n{self.item['size']} {self.item['sha256']} {self.resource}\n".encode("ascii")
        self.assertEqual(expected, subject.budget_bytes(approval))
        self.assertIsNone(subject.budget_bytes(None))
        self.assertIsNone(subject.budget_bytes(approval, "bootstrap-b"))
        second = copy.deepcopy(self.item); second["resource"] = "META-INF/aaa/random.data"
        copied = copy.deepcopy(approval.inventory); copied["resources"].append(second)
        both = subject.Approval(copied, approval.inventory_sha256, approval.evidence_sha256)
        self.assertEqual(sorted((second["resource"], self.resource)),
                         [line.split(" ")[2] for line in subject.budget_bytes(both).decode().splitlines()[1:]])

    def test_assembly_rejects_missing_or_changed_b_package_or_payload_budget(self):
        args = self.package_args()
        b_original = args.bootstrap_b.read_bytes()
        package_budget = args.package / subject.BUDGET_FILENAME
        original_budget = package_budget.read_bytes()
        for value in (None, original_budget + b"extra\n"):
            entries = pack.read_zip(b_original, "B")
            if value is None: entries.pop(subject.BUDGET_RESOURCE)
            else: entries[subject.BUDGET_RESOURCE] = value
            args.bootstrap_b.write_bytes(pack.zip_bytes(entries))
            with self.assertRaisesRegex(ValueError, "Bootstrap-B native budget"): pack.assemble(args)
        args.bootstrap_b.write_bytes(b_original)
        package_budget.write_bytes(original_budget + b"extra\n")
        with self.assertRaisesRegex(ValueError, "Packaged native budget"): pack.assemble(args)
        package_budget.write_bytes(original_budget)
        manifest = json.loads((args.package / "package.json").read_bytes())
        entry = manifest["payloads"][0]
        path = args.package / entry["filename"]
        values = pack.read_zip(path.read_bytes(), "payload", self.load()); values.pop(subject.BUDGET_RESOURCE)
        changed = pack.zip_bytes(values); path.write_bytes(changed)
        entry.update(size=len(changed), sha256=subject.sha(changed))
        (args.package / "package.json").write_text(json.dumps(manifest))
        validation_path = args.package / "java-validation.json"
        validation = json.loads(validation_path.read_bytes()); validation["payload_a_sha256"] = entry["sha256"]
        validation_path.write_text(json.dumps(validation))
        with self.assertRaisesRegex(ValueError, "Native budget must appear"): pack.assemble(args)
        self.assertFalse(args.output.exists())

    def test_prepare_places_reviewed_index_in_first_part_and_copies_exact_package_file(self):
        def clazz(name):
            # Minimal never-executed Java21 class, with an intermediary constant-pool reference.
            values = (name, "java/lang/Object", "net/minecraft/class_1")
            pool = b"".join(b"\x01" + struct.pack(">H", len(value)) + value.encode() + b"\x07" + struct.pack(">H", 1 + 2 * i)
                            for i, value in enumerate(values))
            return b"\xca\xfe\xba\xbe" + struct.pack(">HHH", 0, 65, 7) + pool + struct.pack(">HHHHHHH", 0x21, 2, 4, 0, 0, 0, 0)
        loader = clazz(self.loader[:-6]); self.entries[self.loader] = loader
        (self.root / "loader").write_bytes(loader)
        self.item["loader_sha256"] = subject.sha(loader)
        self.approved["evidence"]["loader"].update(size=len(loader), sha256=subject.sha(loader))
        custody = json.loads(self.evidence["custody"]); custody["loader_sha256"] = subject.sha(loader)
        raw = json.dumps(custody).encode(); (self.root / "custody").write_bytes(raw)
        self.item["custody_sha256"] = subject.sha(raw)
        self.approved["evidence"]["custody"].update(size=len(raw), sha256=subject.sha(raw))
        self.write()
        native_budget = subject.budget_bytes(self.load())
        libraries = {"META-INF/jars/jna.jar": pack.zip_bytes({"com/sun/jna/Native.class": clazz("com/sun/jna/Native")}),
                     "META-INF/jars/oshi.jar": pack.zip_bytes({"oshi/SystemInfo.class": clazz("oshi/SystemInfo")})}
        metadata = {"entrypoints": {"client": ["fixture.client.Main"]}, "jars": [{"file": name} for name in libraries]}
        entries = self.entries | libraries | {"fabric.mod.json": json.dumps(metadata).encode(),
            "fixture/client/Main.class": clazz("fixture/client/Main"),
            "dev/celestebeta/host/Bridge.class": clazz("dev/celestebeta/host/Bridge"),
            "dev/redstones/mediaplayerinfo/impl/win/WindowsMediaPlayerInfo.class": clazz("dev/redstones/mediaplayerinfo/impl/win/WindowsMediaPlayerInfo")}
        source = self.root / "runtime.jar"; source.write_bytes(pack.zip_bytes(entries))
        args = SimpleNamespace(input=source, output=self.root / "prepared", release_id="fixture-release-1", client_version="fixture",
            payload_entrypoint="fixture.client.Main", validation_only=True, base_url=None, server_key=None, descriptor_module=None,
            start_method="start", ready_method="ready", stopped_method="stopped", stop_method="stop", status_method="status",
            native_auth_inventory=self.inventory_path, native_auth_inventory_sha256=self.inventory_hash,
            native_auth_evidence=self.index_path, native_auth_evidence_sha256=self.index_hash)
        with patch.object(pack, "descriptor", return_value=b"fixture descriptor, no auth authority"):
            pack.prepare(args)
        first = pack.read_zip((args.output / "payload-a.bin").read_bytes(), "first", self.load())
        second = pack.read_zip((args.output / "payload-b.bin").read_bytes(), "second", self.load())
        self.assertEqual(native_budget, first[subject.BUDGET_RESOURCE])
        self.assertNotIn(subject.BUDGET_RESOURCE, second)
        self.assertEqual(native_budget, (args.output / subject.BUDGET_FILENAME).read_bytes())

    def test_assembly_rejects_index_moved_to_second_part_even_with_updated_hashes(self):
        args = self.package_args()
        manifest = json.loads((args.package / "package.json").read_bytes())
        values = [pack.read_zip((args.package / part["filename"]).read_bytes(), "part", self.load())
                  for part in manifest["payloads"]]
        values[1][subject.BUDGET_RESOURCE] = values[0].pop(subject.BUDGET_RESOURCE)
        for part, entries in zip(manifest["payloads"], values):
            data = pack.zip_bytes(entries); (args.package / part["filename"]).write_bytes(data)
            part.update(size=len(data), sha256=subject.sha(data))
        (args.package / "package.json").write_text(json.dumps(manifest))
        validation_path = args.package / "java-validation.json"
        validation = json.loads(validation_path.read_bytes())
        for index, name in enumerate(("payload_a_sha256", "payload_b_sha256")):
            validation[name] = manifest["payloads"][index]["sha256"]
        validation_path.write_text(json.dumps(validation))
        with self.assertRaisesRegex(ValueError, "first payload part"): pack.assemble(args)
        self.assertFalse(args.output.exists())

    def test_expanded_archive_bound_checked_before_more_entry_reads(self):
        data = pack.zip_bytes({"a": b"a" * 100, "b": b"b" * 100})
        jar = self.root / "expanded.jar"; jar.write_bytes(data)
        with patch.object(pack, "MAX_TOTAL", 199), self.assertRaisesRegex(ValueError, "128 MiB"):
            pack.read_zip(data, "expanded")
        # Compressed file remains under128 so this exercises expanded bound.
        with patch.object(pipeline, "MAX_JAR", 199), patch.object(pipeline, "read", return_value=data), \
                self.assertRaisesRegex(ValueError, "expanded size"):
            pipeline.archive(jar)

